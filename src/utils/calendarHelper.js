/**
 * Calendar and Deadline Utilities
 * Supports .ics file generation, Google Calendar direct links, and relative deadline calculation.
 */

export function calculateRelativeDeadline(receivedDateStr, deadlineDays = 30) {
  const baseDate = receivedDateStr ? new Date(receivedDateStr) : new Date();
  if (isNaN(baseDate.getTime())) {
    return {
      dueDate: new Date(Date.now() + deadlineDays * 86400000),
      daysRemaining: deadlineDays,
      formattedDate: new Date(Date.now() + deadlineDays * 86400000).toLocaleDateString('en-US', {
        month: 'short',
        day: 'numeric',
        year: 'numeric'
      })
    };
  }

  const dueDate = new Date(baseDate.getTime() + deadlineDays * 86400000);
  const now = new Date();
  const diffTime = dueDate.getTime() - now.getTime();
  const daysRemaining = Math.max(0, Math.ceil(diffTime / (1000 * 60 * 60 * 24)));

  return {
    dueDate,
    daysRemaining,
    formattedDate: dueDate.toLocaleDateString('en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric'
    })
  };
}

export function generateGoogleCalendarUrl(title, description, dueDate) {
  const dateObj = dueDate instanceof Date ? dueDate : new Date(dueDate);
  const startStr = dateObj.toISOString().replace(/-|:|\.\d+/g, '').substring(0, 8);
  const nextDay = new Date(dateObj.getTime() + 86400000);
  const endStr = nextDay.toISOString().replace(/-|:|\.\d+/g, '').substring(0, 8);

  const params = new URLSearchParams({
    action: 'TEMPLATE',
    text: `⚠️ Jargon Breaker Deadline: ${title}`,
    details: `${description}\n\nGenerated by Jargon Breaker AI.`,
    dates: `${startStr}/${endStr}`
  });

  return `https://calendar.google.com/calendar/render?${params.toString()}`;
}

export function downloadIcsFile(title, description, dueDate) {
  const dateObj = dueDate instanceof Date ? dueDate : new Date(dueDate);
  const year = dateObj.getFullYear();
  const month = String(dateObj.getMonth() + 1).padStart(2, '0');
  const day = String(dateObj.getDate()).padStart(2, '0');
  const dateString = `${year}${month}${day}`;

  const icsContent = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//Jargon Breaker//AI Legal Deadline Tracker//EN',
    'CALSCALE:GREGORIAN',
    'BEGIN:VEVENT',
    `UID:${Date.now()}@jargonbreaker.ai`,
    `DTSTAMP:${dateString}T090000Z`,
    `DTSTART;VALUE=DATE:${dateString}`,
    `DTEND;VALUE=DATE:${dateString}`,
    `SUMMARY:⚠️ Action Deadline: ${title}`,
    `DESCRIPTION:${description.replace(/\n/g, '\\n')}`,
    'STATUS:CONFIRMED',
    'BEGIN:VALARM',
    'TRIGGER:-P2D',
    'ACTION:DISPLAY',
    'DESCRIPTION:Reminder: Legal/Contract deadline approaching in 2 days!',
    'END:VALARM',
    'END:VEVENT',
    'END:VCALENDAR'
  ].join('\r\n');

  const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });
  const link = document.createElement('a');
  link.href = window.URL.createObjectURL(blob);
  link.setAttribute('download', `deadline-${title.toLowerCase().replace(/\s+/g, '-').slice(0, 20)}.ics`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
